/**
 * Configuration for the image pipeline (scripts/images.mjs).
 *
 * Sources live in assets-src/images/ (flat). Every image is identified by its
 * id (= source filename without extension) and is emitted to public/img/ as
 *
 *   <id>-<width>.<hash8>.avif|webp   one file per ladder rung and format
 *   <id>.<hash8>.jpg|png             ONE fallback, at the middle rung
 *
 * hash8 is a content hash of source bytes + this entry + encoder versions, so
 * changing any input changes every URL of that image (safe for immutable
 * caching) and an unchanged input is never re-encoded.
 *
 * Rules the script enforces on `widths`: they are clamped to the intrinsic
 * width of the source (never upscale) and de-duplicated, so a rung larger than
 * the source collapses to a single variant at the intrinsic size.
 *
 * `display` is only used for the size report (CSS px an image is *rendered* at
 * on a 1440px desktop, after object-fit: cover scaling). It never affects
 * output bytes or hashes.
 */

/** Bump to force every output to be regenerated (folded into all hashes). */
export const PIPELINE_VERSION = 1;

const KB = 1024;

/** Default per-file byte budget; the script fails the run if a file exceeds it. */
export const DEFAULT_BUDGET = 200 * KB;

/**
 * Encoder options per format and kind. `quality` comes from each image entry.
 * Note: sharp's PNG `effort` implies palette (indexed) output.
 */
export const encoders = {
  avif: {
    photo: { effort: 6, chromaSubsampling: "4:2:0" },
    // Cut-outs and logos have hard coloured edges: keep full chroma resolution.
    alpha: { effort: 6, chromaSubsampling: "4:4:4" },
  },
  webp: {
    photo: { effort: 6 },
    // alphaQuality 100 makes libwebp ~50x slower for ~5% smaller files; 90 is visually lossless for cut-outs.
    alpha: { effort: 6, alphaQuality: 90 },
    lossless: { effort: 6, lossless: true },
  },
  jpeg: {
    photo: { mozjpeg: true },
  },
  png: {
    alpha: { compressionLevel: 9, palette: true, effort: 10, colours: 256, dither: 1 },
    lossless: { compressionLevel: 9, adaptiveFiltering: true },
  },
};

const PHOTO_QUALITY = { avif: 50, webp: 74, jpeg: 72 };
const ALPHA_QUALITY = { avif: 50, webp: 74, png: 90 };

/** Opaque photograph: avif + webp per rung, one jpeg fallback. */
const photo = (id, widths, display, extra = {}) => ({
  id,
  source: `${id}.jpg`,
  kind: "photo",
  widths,
  formats: ["avif", "webp", "jpeg"],
  quality: { ...PHOTO_QUALITY },
  display,
  ...extra,
});

/** Image with real transparency: alpha-capable avif/webp per rung, one png fallback. */
const alpha = (id, widths, display, extra = {}) => ({
  id,
  source: `${id}.png`,
  kind: "alpha",
  widths,
  formats: ["avif", "webp", "png"],
  quality: { ...ALPHA_QUALITY },
  display,
  ...extra,
});

/** Preshoot thumbnails carry baked-in small text, so avif gets a little more quality. */
const preshoot = (n) =>
  photo(`pre${n}`, [366, 549, 732], [366], { quality: { ...PHOTO_QUALITY, avif: 55 } });

